#!/usr/bin/env python3
# gen_testshell.py - build the private offscreen test shell for DeckMain.qml.
#
# Usage: gen_testshell.py --worktree ROOT --mirror DIR [--width W] [--height H]
#
# DIR is wiped and rebuilt, but only when it is a previous mirror (it carries
# the marker file) or empty. Layout written under DIR:
#   shell.qml                      ShellRoot: test DeckMain + optional scenario
#   nexuslink.hud/v5/<entry>       symlink to every entry of the real v5/, except DeckMain.qml
#   nexuslink.hud/v5/DeckMain.qml  test copy, derived from the CURRENT real file at run time
#   nexuslink.hud/v4               symlink to the real v4/ (ScreenRoles.js)
#   imports/NexusHud/V5            symlink to the real v5/kit    (QML_IMPORT_PATH root)
#   imports/NexusHud/fonts         symlink to the real v5/fonts
#   GENERATED.txt                  audit list of every change made to DeckMain.qml
#
# Test copy rules:
#   - "PanelWindow {" (the one at the top of the file) becomes "FloatingWindow {",
#     the only window type that loads under QT_QPA_PLATFORM=offscreen. visible,
#     width, height and title are added.
#   - Direct children of that window that FloatingWindow does not have are
#     dropped: screen, anchors {...}, exclusionMode, WlrLayershell.* (all of it).
#   - WlrLayershell.keyboardFocus: <expr> is dropped as a binding and becomes a
#     plain window property "keyboardFocusProbe: <expr>". The root object exposes
#     it as hud.keyboardFocusProbe and the window as hud.testPanel, so a scenario
#     can read what the real binding would evaluate to.
#   - Every change is printed as a WARN line on stderr and written to GENERATED.txt.
#
# Stdout: "MIRROR <dir>". Stderr: WARN lines (changes) and, on failure, one ERROR
# line. Exit: 0 built, 3 failed.

import argparse
import os
import re
import shutil
import sys

MARKER = ".deckmain-shell-mirror"

SHELL_QML = """import QtQuick
import Quickshell
import "nexuslink.hud/v5"

// Generated by tools/linux/deckmain-shell/gen_testshell.py. Do not edit here.
ShellRoot {
    id: root

    function envOr(name, dflt) {
        var v = Quickshell.env(name)
        return (v === null || v === undefined || String(v) === "") ? dflt : String(v)
    }

    // Scenario log helper: every line it prints starts with "SCENARIO ".
    function log(msg) {
        console.log("SCENARIO " + msg)
    }

    // The test copy of DeckMain.qml (its window is a FloatingWindow). The
    // directory import also brings DeckSurface and the other v5 files in.
    DeckMain {
        id: deck
    }

    // Optional scenario, from DECKMAIN_SCENARIO. It gets hud and log.
    Loader {
        id: scenario
        onStatusChanged: {
            if (status === Loader.Error)
                console.log("ERROR scenario failed to load: " + source)
        }
    }

    Component.onCompleted: {
        var src = root.envOr("DECKMAIN_SCENARIO", "")
        if (src !== "") {
            var url = src.indexOf("file://") === 0 ? src : "file://" + src
            scenario.setSource(url, { "hud": deck, "log": root.log })
        }
    }
}
"""

# Direct children of the window (brace depth 1) that FloatingWindow cannot take.
DROP_IN_WINDOW = [
    (re.compile(r"^\s*screen\s*:"),
     "screen: FloatingWindow is not bound to an output"),
    (re.compile(r"^\s*anchors\s*\{"),
     "anchors {...}: layer-shell anchoring, FloatingWindow is a plain toplevel"),
    (re.compile(r"^\s*exclusionMode\s*:"),
     "exclusionMode: layer-shell only"),
    (re.compile(r"^\s*WlrLayershell\."),
     "WlrLayershell attached property: layer-shell only"),
]
KEYFOCUS_RE = re.compile(r"^\s*WlrLayershell\.keyboardFocus\s*:\s*(.+?)\s*;?\s*$")
PANEL_RE = re.compile(r"^(\s*)PanelWindow\s*\{")
ID_RE = re.compile(r"^\s*id\s*:\s*([A-Za-z_]\w*)\s*$")
ROOT_RE = re.compile(r"^[A-Za-z_][\w.]*\s*\{")
STR_RE = re.compile(r"\"(?:[^\"\\]|\\.)*\"|'(?:[^'\\]|\\.)*'")


class GenError(Exception):
    pass


def code_of(line):
    """The line without a trailing // comment (a // inside a string is kept)."""
    out = []
    quote = None
    i = 0
    while i < len(line):
        c = line[i]
        if quote:
            out.append(c)
            if c == "\\" and i + 1 < len(line):
                out.append(line[i + 1])
                i += 2
                continue
            if c == quote:
                quote = None
        elif c in "\"'":
            quote = c
            out.append(c)
        elif line.startswith("//", i):
            break
        else:
            out.append(c)
        i += 1
    return "".join(out)


def braces(line):
    code = STR_RE.sub('""', code_of(line))
    return code.count("{") - code.count("}")


def transform(src, width, height):
    """Return (new_source, notes). Raises GenError when the file has no single PanelWindow."""
    lines = src.split("\n")
    starts = [i for i, l in enumerate(lines) if PANEL_RE.match(l)]
    if len(starts) != 1:
        raise GenError("DeckMain.qml must have exactly one 'PanelWindow {' line, found %d"
                       % len(starts))
    p = starts[0]
    opening = PANEL_RE.match(lines[p])
    indent = opening.group(1) if opening else ""
    notes = []
    body = []
    probe = None
    window_id = None
    own_id = False
    depth = braces(lines[p])
    end = None
    for j in range(p + 1, len(lines)):
        line = lines[j]
        d0 = depth
        depth += braces(line)
        code = code_of(line).strip()
        if d0 == 1 and code:
            m = KEYFOCUS_RE.match(code)
            if m:
                probe = m.group(1)
                notes.append("WARN keyboardFocus binding dropped, kept as probe only: "
                             "WlrLayershell.keyboardFocus: %s" % probe)
                if depth == 0:
                    end = j
                    break
                continue
            reason = None
            for rx, why in DROP_IN_WINDOW:
                if rx.match(code):
                    reason = why
                    break
            if reason:
                notes.append("dropped in test copy (%s): %s" % (reason, line.strip()))
                if depth == 0:
                    end = j
                    break
                continue
            mid = ID_RE.match(code)
            if mid:
                window_id = mid.group(1)
                own_id = True
        body.append(line)
        if depth == 0:
            end = j
            break
    if end is None:
        raise GenError("could not find the end of the PanelWindow block")
    if not own_id:
        window_id = "testPanel"
        notes.append("added window id: testPanel")
    inner = indent + "    "
    head = [
        indent + "FloatingWindow {",
        inner + "// test copy (generated): offscreen toplevel in place of the layer-shell panel",
        inner + "visible: true",
        inner + "implicitWidth: %d" % width,
        inner + "implicitHeight: %d" % height,
        inner + 'title: "nexuslink-hud-v5 test"',
    ]
    if not own_id:
        head.append(inner + "id: testPanel")
    head.append(inner + "property var keyboardFocusProbe: %s"
                % (probe if probe is not None else "null"))
    if probe is None:
        notes.append("no WlrLayershell.keyboardFocus line in the real file: probe is null")
    # body already ends with the window's closing brace (depth back to 0).
    new = lines[:p] + head + body + lines[end + 1:]
    # Expose the window and its probe from the root object.
    r = next((i for i, l in enumerate(new) if ROOT_RE.match(l) and not l.startswith("import")), None)
    if r is None:
        raise GenError("no root object found in DeckMain.qml")
    rootin = "    "
    expose = [
        rootin + "// test copy (generated): the window and its keyboardFocus probe, for scenarios",
        rootin + "readonly property var testPanel: %s" % window_id,
        rootin + "readonly property var keyboardFocusProbe: %s.keyboardFocusProbe" % window_id,
    ]
    new = new[:r + 1] + expose + new[r + 1:]
    return "\n".join(new), notes


def build(root, mirror, width, height):
    v5 = os.path.join(root, "nexuslink.hud", "v5")
    v4 = os.path.join(root, "nexuslink.hud", "v4")
    for need in (v5, v4, os.path.join(v5, "kit"), os.path.join(v5, "fonts"),
                 os.path.join(v5, "DeckMain.qml")):
        if not os.path.exists(need):
            raise GenError("missing in worktree: %s" % need)
    with open(os.path.join(v5, "DeckMain.qml"), encoding="utf-8") as fh:
        src = fh.read()
    test_copy, notes = transform(src, width, height)

    if os.path.lexists(mirror):
        marked = os.path.isfile(os.path.join(mirror, MARKER))
        if not marked and os.listdir(mirror):
            raise GenError("refusing to wipe %s: not a deckmain-shell mirror" % mirror)
        shutil.rmtree(mirror)
    os.makedirs(os.path.join(mirror, "nexuslink.hud", "v5"))
    with open(os.path.join(mirror, MARKER), "w", encoding="utf-8") as fh:
        fh.write("deckmain-shell mirror of %s\n" % root)
    with open(os.path.join(mirror, "shell.qml"), "w", encoding="utf-8") as fh:
        fh.write(SHELL_QML)

    v5m = os.path.join(mirror, "nexuslink.hud", "v5")
    linked = []
    for name in sorted(os.listdir(v5)):
        if name == "DeckMain.qml":
            continue
        os.symlink(os.path.join(v5, name), os.path.join(v5m, name))
        linked.append(name)
    with open(os.path.join(v5m, "DeckMain.qml"), "w", encoding="utf-8") as fh:
        fh.write(test_copy)
    os.symlink(v4, os.path.join(mirror, "nexuslink.hud", "v4"))
    imp = os.path.join(mirror, "imports", "NexusHud")
    os.makedirs(imp)
    os.symlink(os.path.join(v5, "kit"), os.path.join(imp, "V5"))
    os.symlink(os.path.join(v5, "fonts"), os.path.join(imp, "fonts"))

    with open(os.path.join(mirror, "GENERATED.txt"), "w", encoding="utf-8") as fh:
        fh.write("test copy of %s, window %dx%d\n" % (os.path.join(v5, "DeckMain.qml"), width, height))
        fh.write("symlinked from v5: %s\n" % " ".join(linked))
        fh.write("symlinked: nexuslink.hud/v4 and imports/NexusHud/{V5,fonts}\n")
        for n in notes:
            fh.write(n + "\n")
    return notes


def main():
    ap = argparse.ArgumentParser(description="Build the test mirror for DeckMain.qml.")
    ap.add_argument("--worktree", required=True)
    ap.add_argument("--mirror", required=True)
    ap.add_argument("--width", type=int, default=2560)
    ap.add_argument("--height", type=int, default=1440)
    a = ap.parse_args()
    root = os.path.realpath(a.worktree)
    mirror = os.path.abspath(a.mirror)
    try:
        notes = build(root, mirror, a.width, a.height)
    except (GenError, OSError) as exc:
        sys.stderr.write("ERROR generator: %s\n" % exc)
        return 3
    for n in notes:
        text = n[len("WARN "):] if n.startswith("WARN ") else n
        sys.stderr.write("WARN test-copy: %s\n" % text)
    sys.stdout.write("MIRROR %s\n" % mirror)
    return 0


if __name__ == "__main__":
    sys.exit(main())
