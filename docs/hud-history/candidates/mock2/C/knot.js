function drawKnot(cv, px, lit){
  const cols=48, rows=KNOT_ROWS.length, dpr=window.devicePixelRatio||1;
  cv.width=cols*px*dpr; cv.height=rows*px*dpr;
  cv.style.width=(cols*px)+'px'; cv.style.height=(rows*px)+'px';
  const x=cv.getContext('2d'); x.setTransform(dpr,0,0,dpr,0,0);
  lit = (lit===undefined)?0.5:lit;
  const grout=Math.max(.6,px*.08);
  for(let r=0;r<rows;r++)for(let c=0;c<cols;c++){
    if(KNOT_ROWS[r].charAt(c)!=='#')continue;
    const X=c*px, Y=r*px, S=px;
    x.fillStyle='rgba(0,0,0,0.46)';                 /* engraved pit   */
    x.fillRect(X+grout*.5, Y+grout*.5, S-grout, S-grout);
    x.fillStyle='rgba(255,207,140,0.075)';          /* low light catch */
    x.fillRect(X+grout*.5, Y+S-grout*1.4, S-grout, 1);
    const n=((r*31+c*17)%13)/13;                     /* per-cell falloff */
    x.fillStyle='rgba(255,176,84,'+(lit*(0.82+0.18*n)).toFixed(3)+')';
    x.fillRect(X+grout, Y+grout, S-2*grout, S-2*grout);
    x.fillStyle='rgba(255,150,60,0.10)';            /* warm edge       */
    x.fillRect(X+grout, Y+grout, S-2*grout, 1);
  }
}
