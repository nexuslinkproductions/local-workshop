#!/usr/bin/env bash
# run-challengers.sh — bakeoff42 challengers: ornith-9b, ministral3-14b (gemma NOT re-run; compare vs results/prompt-v2.json).
# GPU phases run under flock -x (one at a time). gate_check never forced. watchdog thresholds untouched.
# Suite phase uses a derived llama-swap config (bench/bakeoff42/config.suite-<id>.yaml) in which the challenger
# also answers the Chief profile's auxiliary model id "gemma4-12b" (alias). Reason: profile aux tasks are pinned to
# gemma4-12b on :18080, which would evict the challenger mid-suite (seen 16:58, log in ABORTED-1-*). Profile untouched.
set -uo pipefail
LAB=/home/nexuslink/NEXUS_AI_CENTER/LOCAL-AI-LAB
BO=$LAB/bench/bakeoff42
LOGD=$BO/logs; mkdir -p "$LOGD"
cd "$LAB" || exit 2
source bench/gate.sh
set +u; . bench/configs/sycl-env.sh; set -u
IMG="$HOME/.hermes/cache/scratch/gt-live-2026-10-13.png"
MIN_FREE=750; BREACH_FREE=750   # Marcel 21:00 floor (was 900)
BIG_CHARS=132000   # ~29.5K tokens: largest Chief-suite prompt seen was 29219 tokens

log(){ echo "[$(date +%T)] $*" | tee -a "$LOGD/challengers.log"; }

model_args(){
  case "$1" in
    ornith-9b)
      M=$LAB/models/llm/ornith-ai/Ornith-1.5-9B-GGUF/Ornith-1.5-9B-Q4_K_M.gguf
      MM=$LAB/models/llm/ornith-ai/Ornith-1.5-9B-GGUF/mmproj-Ornith-1.5-9B-BF16.gguf
      KV="${ORNITH_KV:-q4_0}"; PORT=18150; LADDER="${ORNITH_LADDER:-262144}"; MMCPU="${ORNITH_MMCPU---mmproj-cpu}"; export BAKEOFF_EXTRA="${ORNITH_EXTRA--ub 512 -b 512}" ;;   # Marcel 19:08: 256K only, use the whole system (vision encoder on CPU); q8_0 KV at 256K = ~4.6 GB, q4_0 = ~2.4 GB
    ministral3-14b)
      M=$LAB/models/llm/mistralai/Ministral-3-14B-Instruct-2512-GGUF/Ministral-3-14B-Instruct-2512-Q4_K_M.gguf
      MM=$LAB/models/llm/mistralai/Ministral-3-14B-Instruct-2512-GGUF/Ministral-3-14B-Instruct-2512-BF16-mmproj.gguf
      KV=q4_0; PORT=18151; LADDER="16384 8192"; MMCPU="--mmproj-cpu" ;;
  esac
}

gate_wait(){
  local i
  for i in $(seq 1 60); do gate_check && return 0; log "gate refused, waiting 60 s (attempt $i)"; sleep 60; done
  return 1
}

stop_stack(){  # only the llama-swap this driver started (pid file), then its llama-server children on the 181xx pool
  if [ -f "$BO/llama-swap.pid" ]; then
    local P; P=$(cat "$BO/llama-swap.pid")
    kill -TERM "$P" 2>/dev/null; sleep 3; kill -KILL "$P" 2>/dev/null; rm -f "$BO/llama-swap.pid"
  fi
  pkill -TERM -f '[l]lama-server.*--port 18' 2>/dev/null; sleep 2
  pkill -KILL -f '[l]lama-server.*--port 18' 2>/dev/null
}

start_sampler(){ rm -f "$2"; setsid nohup python3 "$BO/vram-sampler.py" "$1" "$2" >/dev/null 2>&1 & SAMP=$!; }
stop_sampler(){ kill "$SAMP" 2>/dev/null; wait "$SAMP" 2>/dev/null; SAMP=""; }
min_free(){
  python3 -c 'import sys
v=[int(l.split(",")[1]) for l in open(sys.argv[1]) if l[0].isdigit()]   # negatives = overcommit, keep them
print(min(v) if v else "NA", len(v))' "$1"
}
idle_free(){ python3 bench/arc-vram.py 2>/dev/null | sed -n 's/.*free=\([0-9]*\).*/\1/p'; }
predict_free(){  # main mmproj_bytes kv ctx idle
  python3 "$BO/pick_ctx.py" "$1" "$2" "$3" "$5" 2>/dev/null | sed -n "s/.*ctx *$4: .*free~ *\(-\?[0-9.]*\).*/\1/p" | head -1
}

set_ctx_in_config(){  # id ctx -> serve/config.yaml (cmd + capabilities of that block only)
  python3 - "$1" "$2" <<'PY'
import re, sys
mid, ctx = sys.argv[1], sys.argv[2]
p = "serve/config.yaml"; s = open(p).read()
start = s.index(f'  "{mid}":')
nxt = s.find('\n  "', start + 5)
end = len(s) if nxt < 0 else nxt
blk = s[start:end]
blk = re.sub(r'(bakeoff-launch\.sh \$\{PORT\} )\d+', lambda m: m.group(1) + ctx, blk)
blk = re.sub(r'(capabilities: \{ in: \[text, image\], out: \[text\], tools: true, context: )\d+', lambda m: m.group(1) + ctx, blk)
open(p, "w").write(s[:start] + blk + s[end:])
PY
}

make_suite_cfg(){  # id ctx -> bench/bakeoff42/config.suite-<id>.yaml (challenger only + alias gemma4-12b)
  python3 - "$1" "$2" "$M" "$MM" "$KV" "$MMCPU" "$LAB" <<'PY'
import sys
mid, ctx, M, MM, KV, MMCPU, LAB = sys.argv[1:8]
mm_cpu = " --mmproj-cpu" if MMCPU else ""
think_key = mid
txt = f"""# GENERATED by bench/bakeoff42/run-challengers.sh — suite-only llama-swap config (one model).
# Alias gemma4-12b: the Chief profile pins its auxiliary tasks to that id; route them to the model under test.
healthCheckTimeout: 900
logLevel: info
logToStdout: both
globalTTL: 600
unloadTimeout: 10
startPort: 18100
models:
  "{mid}":
    name: "bakeoff42 suite: {mid} ctx {ctx}"
    cmd: >
      {LAB}/serve/gate-run.sh
      {LAB}/serve/bakeoff-launch.sh ${{PORT}} {ctx} {M} {MM} {KV}{mm_cpu}
    ttl: 600
    aliases: ["gemma4-12b"]
    filters:
      setParamsByID:
        {think_key}: {{ chat_template_kwargs: {{ enable_thinking: false }} }}
        gemma4-12b: {{ chat_template_kwargs: {{ enable_thinking: false }} }}
    capabilities: {{ in: [text, image], out: [text], tools: true, context: {ctx} }}
"""
open(f"{LAB}/bench/bakeoff42/config.suite-{mid}.yaml", "w").write(txt)
PY
  llama-swap -config "$BO/config.suite-$1.yaml" -validate 2>&1 | tail -1
}

phase_direct(){
  local id="$1"; model_args "$id"
  rm -f "$LOGD/ctx-$id.txt"   # stale ctx from an older run made swap start at 49152 after a failed direct (19:23)
  gate_wait || { log "$id direct: GATE REFUSED 60 min, skip"; return 3; }
  io_quiet_wait || { log "$id direct: IO busy, skip"; return 3; }
  pgrep -f '[l]lama-server' >/dev/null && { log "$id direct: llama-server running, skip"; return 3; }
  local idle; idle=$(idle_free)
  log "$id direct: idle free VRAM ${idle} MiB (nothing loaded)"
  local mmb=0; [ -z "$MMCPU" ] && mmb=$(stat -c%s "$MM")
  local chosen="" ctx pf
  for ctx in $LADDER; do
    pf=$(predict_free "$M" "$mmb" "$KV" "$ctx" "$idle")
    log "$id ctx $ctx predicted free ${pf} MiB"
    if [ -z "$chosen" ] && awk -v a="${pf:-0}" -v b="$MIN_FREE" 'BEGIN{exit !(a>=b)}'; then chosen="$ctx"; fi
  done
  chosen="${LADDER%% *}"   # measured smoke decides; pick_ctx assumes full-attention KV (wrong for hybrid Ornith): logged only
  for ctx in $LADDER; do
    [ "$ctx" -gt "$chosen" ] && continue
    rm -f "$LOGD/$id-direct.json"
    rm -f "$LOGD/vram-$id-direct-$ctx.csv"   # sampler appends: a previous variant's minimum leaked into this one (19:36)
    start_sampler "$LOGD/vram-$id-direct-$ctx.csv" "$LOGD/BREACH-$id"
    log "$id direct smoke ctx $ctx KV $KV ${MMCPU:-mmproj-gpu} (4K + ~29.5K prefill)"
    python3 "$BO/smoke.py" --id "$id" --model "$M" ${MM:+--mmproj "$MM"} --ctx "$ctx" --kv "$KV" $MMCPU --port "$PORT" --big-chars $BIG_CHARS > "$LOGD/$id-direct-ctx$ctx.out" 2>&1
    local rc=$?
    stop_sampler
    cp -f "$LOGD/$id-direct.json" "$LOGD/$id-direct-ctx$ctx.json" 2>/dev/null
    local mf; mf=$(min_free "$LOGD/vram-$id-direct-$ctx.csv")
    log "$id direct ctx $ctx rc=$rc min_free=${mf}"
    pkill -TERM -f "[l]lama-server.*--port $PORT" 2>/dev/null; sleep 3
    if [ -e "$LOGD/BREACH-$id" ]; then log "$id BREACH: $(cat "$LOGD/BREACH-$id") -- model stopped, reported"; stop_stack; return 5; fi
    if [ "$rc" = 0 ] && awk -v a="${mf%% *}" -v b="$MIN_FREE" 'BEGIN{exit !(a+0>=b)}'; then
      echo "$ctx" > "$LOGD/ctx-$id.txt"; set_ctx_in_config "$id" "$ctx"
      log "$id ctx $ctx ACCEPTED (min free ${mf} >= ${MIN_FREE})"; return 0
    fi
    log "$id ctx $ctx not accepted (rc=$rc min_free=${mf}); stepping down"; sleep 5
  done
  log "$id direct: no ctx met ${MIN_FREE} MiB"; return 4
}

phase_swap(){
  local id="$1"; model_args "$id"
  local ctx; ctx=$(cat "$LOGD/ctx-$id.txt" 2>/dev/null) || { log "$id swap: no ctx file"; return 4; }
  gate_wait || { log "$id swap: GATE REFUSED, skip"; return 3; }
  io_quiet_wait || { log "$id swap: IO busy, skip"; return 3; }
  pgrep -f '[l]lama-server' >/dev/null && { log "$id swap: llama-server running, skip"; return 3; }
  if curl -sf -m 2 http://127.0.0.1:18080/v1/models >/dev/null; then log "$id swap: :18080 already answers (not ours), skip"; return 3; fi
  make_suite_cfg "$id" "$ctx" || { log "$id swap: config invalid"; return 4; }
  rm -f "$LOGD/BREACH-$id"
  start_sampler "$LOGD/vram-$id-swap.csv" "$LOGD/BREACH-$id"
  log "$id swap: llama-swap (suite config, ctx $ctx)"
  setsid llama-swap -config "$BO/config.suite-$id.yaml" -listen 127.0.0.1:18080 > "$LOGD/llama-swap-$id.log" 2>&1 &
  echo $! > "$BO/llama-swap.pid"
  local i; for i in $(seq 1 60); do curl -sf -m 2 http://127.0.0.1:18080/v1/models >/dev/null && break; sleep 1; done
  if ! curl -sf -m 3 http://127.0.0.1:18080/v1/models >/dev/null; then log "$id swap: llama-swap not answering"; stop_sampler; stop_stack; return 4; fi
  python3 "$BO/swap-smoke.py" --model "$id" --image "$IMG" --out "$LOGD/swap-$id.json" > "$LOGD/swap-$id.out" 2>&1
  log "$id swap-smoke rc=$?"
  if [ ! -e "$LOGD/BREACH-$id" ]; then
    log "$id suite: 42 items (ctx $ctx)"
    LC_LOCKED=1 python3 evals/chief/run_suite.py --model "$id" --out "results/bakeoff42-$id.json" > "$LOGD/suite-$id.out" 2>&1
    log "$id suite rc=$?"
  fi
  stop_sampler; stop_stack
  log "$id swap phase min_free=$(min_free "$LOGD/vram-$id-swap.csv")"
  if [ -e "$LOGD/BREACH-$id" ]; then log "$id BREACH in swap/suite: $(cat "$LOGD/BREACH-$id") -- stopped, reported"; return 5; fi
  return 0
}

if [ "${1:-}" = "--phase" ]; then
  shift; ph="$1"; id="$2"
  if [ "$ph" = direct ]; then phase_direct "$id"; else phase_swap "$id"; fi
  exit $?
fi

log "driver start pid $$"
for id in ${CHALLENGERS:-ornith-9b ministral3-14b}; do
  for ph in direct swap; do
    rc=1
    for try in 1 2 3 4 5 6; do
      flock -x -w 3600 bench/.gpu.lock env LC_LOCKED=1 bash "$0" --phase "$ph" "$id"; rc=$?
      [ "$rc" = 1 ] || break
      log "lock wait timed out ($ph $id), retry $try"
    done
    log "phase $ph $id rc=$rc"
  done
done
for id in ${CHALLENGERS:-ornith-9b ministral3-14b}; do
  [ -f "results/bakeoff42-$id.json" ] && python3 evals/chief/run_suite.py --compare results/prompt-v2.json "results/bakeoff42-$id.json" > "$LOGD/compare-gemma-$id.txt" 2>&1
done
log "CHALLENGERS DONE"
